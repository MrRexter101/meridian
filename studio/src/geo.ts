export function project(lat: number, lon: number, rot: number, R: number) {
  const a = (lat * Math.PI) / 180;
  const b = ((lon + rot) * Math.PI) / 180;
  return {
    x: R * Math.cos(a) * Math.sin(b),
    y: -R * Math.sin(a),
    z: Math.cos(a) * Math.cos(b),
  };
}

